def find(code_name):
    nm = NAME2CODE.get(code_name, code_name)
    for seg in ('885','886','881','883'):
        hit = idx[(idx['name']==nm) & idx['ts_code'].str.startswith(seg)]
        if len(hit): return hit.iloc[0]['ts_code']
    return None

anchors = []
for d, lst in {**SEPT, **OCT}.items():
    for bk, v in lst:
        code = find(bk)
        anchors.append((bk, d, v, code))
have = [(bk,d,v,c) for bk,d,v,c in anchors if c and c in cache]
print(f'锚点 {len(anchors)} 个, 可匹配成分 {len(have)} 个, 板块 {len(set(x[0] for x in have))} 个')

# 每锚点: 窗口 n 日(含当日) 的 累计S5/累计S1/累计涨停数
def stats(code, d, n):
    i = tds.index(d)
    win = tds[max(0,i-n+1):i+1]
    cons = set(x[:6] for x in cache[code]['cons'])
    sub = daily[(daily['code6'].isin(cons)) & (daily['trade_date'].isin(win))]
    if len(sub)==0: return None
    s5 = sub.groupby('trade_date')['pct_chg'].sum().sum()
    s1 = sub[sub['pct_chg']>0].groupby('trade_date')['pct_chg'].sum().sum()
    lim = sub[(sub['pct_chg']>=9.8)&(sub['ts_code'].str[:2].isin(['60','00'])) | (sub['pct_chg']>=19.8)].shape[0]
    upn = int((sub['pct_chg']>0).sum())
    return s5, s1, lim, upn

print(f'\n{"窗口":>4} {"口径":<8} {"K中位":>9} {"CV%":>7} {"n":>4}')
best = []
for n in [1,3,5,7,8,10,13]:
    for col, nm in [(0,'S5累计'),(1,'S1累计'),(2,'涨停家次'),(3,'上涨家次')]:
        ks = []
        for bk,d,v,code in have:
            st = stats(code, d, n)
            if not st: continue
            x = st[col]
            if abs(x) < 1e-9: continue
            k = v/x
            if k > 0:  # 只看同号(负锚点单列验证)
                ks.append(k)
        if len(ks) >= 20:
            ks = np.array(ks)
            cv = ks.std()/ks.mean()*100
            best.append((cv, n, nm, np.median(ks), len(ks)))
            print(f'{n:>4} {nm:<8} {np.median(ks):>9.2f} {cv:>7.1f} {len(ks):>4}')
best.sort()
print('\n最优:', f'窗口{best[0][1]}日 {best[0][2]} K={best[0][3]:.2f} CV={best[0][0]:.1f}%')
